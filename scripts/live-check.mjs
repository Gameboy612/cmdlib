import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: '/home/kapak/.cache/ms-playwright/chromium-1187/chrome-linux/chrome', args:['--no-sandbox'] });
const page = await browser.newPage({ viewport:{width:1440,height:900} });
const errors=[], failed=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
page.on('response',r=>{if(r.status()>=400)failed.push([r.status(),r.url()])});
await page.goto('https://wankun.kapakki.com/cmdlib/', {waitUntil:'domcontentloaded', timeout:90000});
await page.waitForTimeout(1000);
const home = await page.evaluate(()=>({title:document.title, url:location.href, fonts:[...document.fonts].filter(f=>f.status==='loaded').length, imgs:[...document.images].every(i=>i.complete&&i.naturalWidth>0)}));
await page.screenshot({path:'/tmp/live-home.png'});
await page.getByRole('link',{name:/Open the editor/i}).first().click();
await page.waitForTimeout(1800);
const editor = await page.evaluate(()=>({url:location.href, title:document.title, cm:!!document.querySelector('.cm-editor'), groups:document.querySelectorAll('.dv-groupview').length}));
await page.getByRole('button',{name:'Demo', exact:true}).click();
await page.waitForTimeout(800);
const demo = await page.locator('text=BOUNTY CLAIMED').count();
await page.screenshot({path:'/tmp/live-editor.png'});
console.log(JSON.stringify({home, editor, demo, errors, failed}, null, 2));
await browser.close();
