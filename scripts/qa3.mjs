import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: '/home/kapak/.cache/ms-playwright/chromium-1187/chrome-linux/chrome', args:['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errs=[]; page.on('pageerror', e=>errs.push(e.message)); page.on('console', m=>{ if(m.type()==='error') errs.push(m.text()); });
await page.goto('http://127.0.0.1:4199/editor/', { waitUntil: 'networkidle' });
await page.waitForTimeout(1500);
await page.locator('.cm-content').click();
await page.keyboard.press('Control+End');
await page.keyboard.press('Enter');
await page.keyboard.type('function ');
await page.waitForTimeout(500);
await page.keyboard.press('Control+Space');
await page.waitForTimeout(700);
const popup = await page.locator('.cm-tooltip-autocomplete').count();
let options = [];
if (popup) options = await page.locator('.cm-tooltip-autocomplete li').allTextContents();
await page.screenshot({ path: '/tmp/q-complete2.png' });
console.log(JSON.stringify({errs, popup, options: options.slice(0,10)}, null, 2));
await browser.close();
