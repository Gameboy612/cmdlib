import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: '/home/kapak/.cache/ms-playwright/chromium-1187/chrome-linux/chrome', args:['--no-sandbox','--disable-dev-shm-usage'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
const errors=[]; const failed=[];
page.on('pageerror',e=>errors.push(e.message)); page.on('console',m=>{if(m.type()==='error')errors.push(m.text())}); page.on('response',r=>{if(r.status()>=400)failed.push([r.status(),r.url()])});
await page.goto('http://127.0.0.1:4199/', { waitUntil: 'networkidle' });
await page.waitForTimeout(900);
await page.screenshot({ path: 'docs/screenshots/landing.png' });
await page.evaluate(() => { const el=document.getElementById('run'); window.scrollTo(0, el.offsetTop + (el.offsetHeight - innerHeight) * 0.96); });
await page.waitForTimeout(1800);
await page.screenshot({ path: 'docs/screenshots/landing-live.png' });
await page.goto('http://127.0.0.1:4199/editor/', { waitUntil: 'networkidle' });
await page.waitForTimeout(1800);
await page.getByRole('button', { name: 'Demo', exact: true }).click();
await page.waitForTimeout(1000);
await page.screenshot({ path: 'docs/screenshots/editor.png' });
const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, deviceScaleFactor: 1 });
await mobile.goto('http://127.0.0.1:4199/', { waitUntil: 'networkidle' });
await mobile.waitForTimeout(700);
await mobile.screenshot({ path: 'docs/screenshots/mobile.png' });
await mobile.goto('http://127.0.0.1:4199/editor/', { waitUntil: 'networkidle' });
await mobile.waitForTimeout(1500);
await mobile.getByRole('tab', { name: 'World' }).click();
await mobile.waitForTimeout(700);
await mobile.screenshot({ path: 'docs/screenshots/mobile-editor.png' });
console.log(JSON.stringify({errors, failed}, null, 2));
await browser.close();
